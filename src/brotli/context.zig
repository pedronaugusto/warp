//! The literal context modes (RFC 7932 §7.1): which of a block type's 64
//! contexts a literal is coded in, from the two bytes before it.

/// A literal block type's context mode, as its 2 bits say.
pub const Mode = enum(u2) { lsb6, msb6, utf8, signed };

/// Each mode's lookup: a literal's context is `t[p1] | t[256 + p2]`, `p1`
/// the byte before it and `p2` the one before that.
pub const lookup: [4][512]u8 = blk: {
    var t: [4][512]u8 = undefined;
    for (0..256) |i| {
        t[0][i] = i & 0x3f;
        t[0][256 + i] = 0;
        t[1][i] = i >> 2;
        t[1][256 + i] = 0;
        t[2][i] = utf8_last[i];
        t[2][256 + i] = utf8_second[i];
        t[3][i] = signed[i] << 3;
        t[3][256 + i] = signed[i];
    }
    break :blk t;
};

