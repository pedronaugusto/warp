test "the lookups give the RFC's contexts" {
    const std = @import("std");
    // ASCII: 4 * context1(p1) + context2(p2): 'e' after 'h' is a lower-case
    // vowel (14) after a lower-case letter (3).
    try std.testing.expectEqual(4 * 14 + 3, lookup[2]['e'] | lookup[2][256 + 'h']);
    try std.testing.expectEqual(0x3f, lookup[0][0xff] | lookup[0][256 + 0xff]);
    try std.testing.expectEqual(0x3f, lookup[1][0xff]);
    try std.testing.expectEqual(63, lookup[3][0xff] | lookup[3][256 + 0xff]);
}
